"""LocalWorkflowRunner for executing deployment DAGs locally.

Replaces Argo workflow execution in local extend mode. For each node in the
deployment manifest (generated by ms-deployment), the runner runs the deploy
script in an hmd-img-projectbuilder container against the single Floci
instance -- except the single core node for ``bom_seeder.CORE_REPO_CLASS``
(``hmd-cli-neuronsphere``), which only ever anchors the core-resource-producing
instance (see ``bom_seeder.LOCAL_CORE_BOM``) and is marked DEPLOYED directly
without executing anything.
"""

